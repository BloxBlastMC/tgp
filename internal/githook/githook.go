// Package githook implements the server-side git hooks. receive-pack runs
// with core.hooksPath pointing at scripts that exec `tgp-server hook <kind>`;
// the hook reads ref updates from stdin and asks the server (over an
// internal HTTP endpoint authenticated with a per-process secret) whether to
// accept them (pre-receive) or tells it what changed (post-receive).
package githook

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"time"
)

// Environment passed from the server to hook processes.
const (
	EnvURL    = "TGP_HOOK_URL"
	EnvSecret = "TGP_HOOK_SECRET"
	EnvRepo   = "TGP_HOOK_REPO_ID"
	EnvUser   = "TGP_HOOK_USER_ID"
	// SecretHeader carries the secret on the internal endpoint.
	SecretHeader = "X-TGP-Hook-Secret"
)

// Kinds of hook tgp installs.
const (
	PreReceive  = "pre-receive"
	PostReceive = "post-receive"
)

const zeroID = "0000000000000000000000000000000000000000"

// Update is one ref update from a push.
type Update struct {
	Old string `json:"old"`
	New string `json:"new"`
	Ref string `json:"ref"`
	// Forced is true when New doesn't contain Old (history rewritten).
	Forced bool `json:"forced"`
}

// IsCreate / IsDelete describe the update.
func (u Update) IsCreate() bool { return u.Old == zeroID }
func (u Update) IsDelete() bool { return u.New == zeroID }

// Request is sent by a hook to the server.
type Request struct {
	RepoID  int64    `json:"repo_id"`
	UserID  int64    `json:"user_id"`
	Updates []Update `json:"updates"`
}

// Response is the server's answer. Messages are shown to the pusher.
type Response struct {
	Allowed  bool     `json:"allowed"`
	Messages []string `json:"messages,omitempty"`
}

// Run executes a hook. It returns the process exit code.
func Run(kind string, stdin io.Reader, stderr io.Writer) int {
	if kind != PreReceive && kind != PostReceive {
		fmt.Fprintf(stderr, "tgp: unknown hook %q\n", kind)
		return 1
	}
	fail := func(format string, args ...any) int {
		fmt.Fprintf(stderr, "tgp: "+format+"\n", args...)
		if kind == PostReceive {
			return 0 // the push already happened; don't report failure
		}
		return 1
	}
	url, secret := os.Getenv(EnvURL), os.Getenv(EnvSecret)
	repoID, _ := strconv.ParseInt(os.Getenv(EnvRepo), 10, 64)
	userID, _ := strconv.ParseInt(os.Getenv(EnvUser), 10, 64)
	if url == "" || secret == "" || repoID == 0 {
		return fail("hook environment missing; pushes must go through tgp-server")
	}
	req := Request{RepoID: repoID, UserID: userID}
	sc := bufio.NewScanner(stdin)
	for sc.Scan() {
		f := strings.Fields(sc.Text())
		if len(f) != 3 {
			continue
		}
		u := Update{Old: f[0], New: f[1], Ref: f[2]}
		if kind == PreReceive && !u.IsCreate() && !u.IsDelete() {
			u.Forced = !isAncestor(u.Old, u.New)
		}
		req.Updates = append(req.Updates, u)
	}
	body, _ := json.Marshal(req)
	hreq, err := http.NewRequest(http.MethodPost, strings.TrimRight(url, "/")+"/internal/hooks/"+kind, bytes.NewReader(body))
	if err != nil {
		return fail("%v", err)
	}
	hreq.Header.Set("Content-Type", "application/json")
	hreq.Header.Set(SecretHeader, secret)
	client := &http.Client{Timeout: 60 * time.Second}
	res, err := client.Do(hreq)
	if err != nil {
		return fail("couldn't reach the server to check this push: %v", err)
	}
	defer res.Body.Close()
	var out Response
	if err := json.NewDecoder(io.LimitReader(res.Body, 1<<20)).Decode(&out); err != nil || res.StatusCode != http.StatusOK {
		return fail("server rejected the hook call (HTTP %d)", res.StatusCode)
	}
	for _, m := range out.Messages {
		fmt.Fprintln(stderr, m)
	}
	if !out.Allowed && kind == PreReceive {
		return 1
	}
	return 0
}

// isAncestor runs inside the repository during pre-receive, where git's
// quarantine environment makes the pushed objects visible.
func isAncestor(old, new string) bool {
	if typ, err := exec.Command("git", "cat-file", "-t", old).Output(); err != nil || strings.TrimSpace(string(typ)) != "commit" {
		return true // tags and other objects: not a history rewrite
	}
	return exec.Command("git", "merge-base", "--is-ancestor", old, new).Run() == nil
}

// WriteScripts installs hook scripts into dir that exec `exe hook <kind>`.
func WriteScripts(dir, exe string) error {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	quoted := "'" + strings.ReplaceAll(exe, "'", `'\''`) + "'"
	for _, kind := range []string{PreReceive, PostReceive} {
		script := "#!/bin/sh\n# Generated by tgp-server. Do not edit.\nexec " + quoted + " hook " + kind + "\n"
		tmp := filepath.Join(dir, "."+kind+".tmp")
		if err := os.WriteFile(tmp, []byte(script), 0o755); err != nil {
			return err
		}
		if err := os.Rename(tmp, filepath.Join(dir, kind)); err != nil {
			return err
		}
	}
	return nil
}
